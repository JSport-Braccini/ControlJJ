export function createInitialTournamentState(tournament: Tournament): TournamentState {
  const isDefault = tournament.id === DEFAULT_TOURNAMENT.id;
  return {
    tournament,
    players: isDefault
      ? INITIAL_PLAYERS
      : [
          {
            id: `p-${tournament.id}-1`,
            tournamentId: tournament.id,
            qrCode: 'JUG-001',
            name: 'Capitán Referente',
            team: 'Equipo Local',
            jerseyNumber: 10,
            position: 'Mediocampista',
            dni: '70000001',
            checkedIn: false,
            duplicateAttempts: 0,
          },
        ],
    spectatorTiers: isDefault
      ? INITIAL_SPECTATOR_TIERS
      : INITIAL_SPECTATOR_TIERS.map((t) => ({
          ...t,
          id: `${t.id}-${tournament.id}`,
          tournamentId: tournament.id,
        })),
    spectatorEntries: isDefault ? INITIAL_SPECTATOR_ENTRIES : [],
    beverages: isDefault
      ? INITIAL_BEVERAGES
      : INITIAL_BEVERAGES.map((b) => ({
          ...b,
          tournamentId: tournament.id,
          soldCount: 0,
        })),
    beverageSales: isDefault ? INITIAL_BEVERAGE_SALES : [],
    expenses: isDefault ? INITIAL_EXPENSES : [],
    scanHistory: [],
  };
}
